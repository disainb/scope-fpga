#!/usr/bin/env python3
"""Generate rtl/msg_rom.v and rtl/msg_ids.vh from the message table below.

Edit the text here, then run:   python3 scripts/gen_msg_rom.py
Both generated files are committed so Vivado users don't need Python.

Placeholders inside messages:
  {name}  -> decimal number from the DEC_VARS list  (encoded as 0x80 | index)
  {$name} -> single character from the CHR_VARS list (encoded as 0xC0 | index)
Each message ends with a 0x00 byte.
"""
import os
import re

DEC_VARS = ["sr", "adc", "ss", "pt", "tl", "th", "ph", "pd", "tp",
            "br", "trig", "n", "d", "col", "nlast", "bus"]
CHR_VARS = ["of", "tm", "te", "ck",
            "b7", "b6", "b5", "b4", "b3", "b2", "b1", "b0",
            "r0", "r1", "r2", "r3", "r4", "r5", "r6", "r7"]

VERSION = "v0.4.1"
REV = "{$r0}{$r1}{$r2}{$r3}{$r4}{$r5}{$r6}{$r7}"

MSGS = [
    ("BANNER", f"\r\nscope-fpga ADC08200 test {VERSION}   (H = help)\r\n"),
    ("STATUS", "OK SR={sr}SPS ADC={adc}Hz SS={ss} PT={pt} OF={$of} TM={$tm} "
               "TE={$te} TL={tl} TH={th} PH={ph} PD={pd} TP={tp} CK={$ck} BR={br}\r\n"),
    ("BUS",    "BUS={bus} D7..D0={$b7}{$b6}{$b5}{$b4}{$b3}{$b2}{$b1}{$b0}\r\n"),
    ("REV",    f"REV={REV}\r\n"),
    ("REVOK",  f"OK REV={REV}\r\n"),
    ("REVLEN", "ERR revision must be 8 characters\r\n"),
    ("FLERR",  "ERR flash write failed\r\n"),
    ("SPC",    "OK SPC - binary packet mode, send TEXT packet or press btn0 to leave\r\n"),
    ("ERR",    "ERR at col {col}\r\n"),
    ("NODATA", "ERR no capture yet\r\n"),
    ("STOP",   "STOPPED\r\n"),
    ("HDR",    "#N={nlast},SR={sr},PT={pt},TRIG={trig}\r\n"),
    ("HDRB",   "#BIN N={nlast},SR={sr},PT={pt},TRIG={trig}\r\n"),
    ("END",    "#END\r\n"),
    ("HELP",
     "Commands, comma separated, end with Enter:\r\n"
     " SR=n[K|M]     sample rate, e.g. SR=200MSPS, SR=10MSPS, SR=500KSPS\r\n"
     " SS=n          samples per capture, 1..16384\r\n"
     " PT=n          pre-trigger samples, 0..SS-1\r\n"
     " OFN OFX OFB   output: decimal lines (plotter), hex, raw binary\r\n"
     " TMA TMN TMI   trigger mode: auto, normal, immediate\r\n"
     " TER TEF       trigger edge: rising, falling\r\n"
     " TL=n          trigger level 0..255\r\n"
     " TH=n          trigger hysteresis 0..255\r\n"
     " PH=n  PHA     capture phase, 2.5 ns steps (0..2*M-1), A=auto\r\n"
     " PD=0|1        ADC power-down\r\n"
     " TP=0|1        test pattern: ramp instead of ADC data\r\n"
     " BR=n          UART baud, e.g. BR=115200 (btn0 restores 921600)\r\n"
     " CK=S|0|1      ADC clock: S=running, 0/1 = held low/high (pin check)\r\n"
     " RB            read the ADC data pins once (bring-up check)\r\n"
     " WR=xxxxxxxx   write the 8-character board revision to flash\r\n"
     " RR            read the board revision\r\n"
     " SPC           switch to binary packet mode (PC application)\r\n"
     " R             run one capture and send it\r\n"
     " C             run continuously, send any key to stop\r\n"
     " D             send the last capture again\r\n"
     " ?             show settings\r\n"
     " H             this help\r\n"
     "Example: SR=10MSPS,SS=1024,OFN,R\r\n"),
]

PH_RE = re.compile(r"\{(\$?)(\w+)\}")


def encode(text):
    out, pos = [], 0
    for m in PH_RE.finditer(text):
        out += [ord(ch) for ch in text[pos:m.start()]]
        is_chr, name = m.group(1) == "$", m.group(2)
        if is_chr:
            out.append(0xC0 | CHR_VARS.index(name))
        else:
            out.append(0x80 | DEC_VARS.index(name))
        pos = m.end()
    out += [ord(ch) for ch in text[pos:]]
    assert all(0 < b < 0x80 for b in out if b < 0x80), "non-ASCII text"
    out.append(0)
    return out


def main():
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "rtl")
    rom, addrs = [], {}
    for name, text in MSGS:
        addrs[name] = len(rom)
        rom += encode(text)
    aw = max(1, (len(rom) - 1).bit_length())

    with open(os.path.join(root, "msg_ids.vh"), "w", newline="\n") as f:
        f.write("// GENERATED by scripts/gen_msg_rom.py - do not edit\n")
        f.write(f"localparam MSG_AW = {aw};\n")
        for name, a in addrs.items():
            f.write(f"localparam [MSG_AW-1:0] MSG_{name} = {aw}'d{a};\n")
        for i, v in enumerate(DEC_VARS):
            f.write(f"localparam [4:0] V_{v.upper()} = 5'd{i};\n")
        for i, v in enumerate(CHR_VARS):
            f.write(f"localparam [4:0] C_{v.upper()} = 5'd{i};\n")

    with open(os.path.join(root, "msg_rom.v"), "w", newline="\n") as f:
        f.write("// GENERATED by scripts/gen_msg_rom.py - do not edit\n")
        f.write("`timescale 1ns / 1ps\n")
        f.write(f"module msg_rom (\n    input  wire          clk,\n"
                f"    input  wire [{aw-1}:0]   addr,\n"
                f"    output reg  [7:0]    data\n);\n")
        f.write("    always @(posedge clk) begin\n        case (addr)\n")
        for a, b in enumerate(rom):
            if b:
                f.write(f"            {aw}'d{a}: data <= 8'h{b:02X};\n")
        f.write("            default: data <= 8'h00;\n        endcase\n    end\nendmodule\n")
    print(f"msg_rom: {len(rom)} bytes, {aw}-bit address")


if __name__ == "__main__":
    main()
